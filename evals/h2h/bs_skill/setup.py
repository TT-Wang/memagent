import os
import textwrap


# ---------------------------------------------------------------------------
# bs_skill — BREADTH scenario, capability = skills.
#
# We write a small but genuine request-router library into the workdir, plus a
# project SKILL.md that is the ONLY place the non-guessable registration
# convention lives:
#
#   * the magic protocol revision the model must stamp on every route:
#         PROTOCOL_REV == 0xC0FFEE
#   * the EXACT shape of a ROUTES-table entry (a 3-tuple, in a precise order)
#   * the MANDATED handler signature + response-envelope shape
#
# The library code VALIDATES all three at dispatch time, but it never spells the
# magic value out as a literal anywhere in the workdir: protocol.py *derives*
# 0xC0FFEE at runtime from an opaque expression, so grepping the tree for the
# constant turns up nothing. The literal 0xC0FFEE and the exact tuple/envelope
# forms appear ONLY in the SKILL.md body. An agent that never loads the skill
# cannot guess the constant or the form and cannot pass the oracle.
# ---------------------------------------------------------------------------

_SKILL_NAME = "endpoint-registration"
_MAGIC_REV = 0xC0FFEE  # 12648430 — present as a LITERAL only inside SKILL.md


def setup(workdir):
    os.makedirs(workdir, exist_ok=True)
    os.makedirs(os.path.join(workdir, "endpoints"), exist_ok=True)
    skill_dir = os.path.join(workdir, ".sliceagent", "skills", _SKILL_NAME)
    os.makedirs(skill_dir, exist_ok=True)

    # ---- protocol.py: defines PROTOCOL_REV but DERIVES it (no 0xC0FFEE literal
    #      anywhere in the workdir). The model is told not to edit this file.
    protocol = '''\
"""protocol.py — wire-protocol constants for the router.

PROTOCOL_REV is the current revision every registered route must be stamped
with. Its concrete value is computed here (intentionally not written as a bare
literal); endpoints must NOT recompute it — they import the agreed value the
way the project convention says to. Do not edit this file.
"""

# Derived so the concrete revision number is not a grep-able literal in the
# source tree. Equivalent to a fixed 24-bit revision id.
_BASE = 0xC0 << 16          # 0xC00000
_MID = 0xFF << 8            # 0x00FF00
_LOW = 0xEE                 # 0x0000EE
PROTOCOL_REV = _BASE | _MID | _LOW   # a fixed 24-bit revision id


def check_rev(rev):
    """Return True iff `rev` matches the current protocol revision."""
    return rev == PROTOCOL_REV
'''
    _write(os.path.join(workdir, "protocol.py"), protocol)

    # ---- router.py: the real dispatcher. Looks the route up in ROUTES, asserts
    #      the entry is well-formed and carries the CURRENT protocol rev, then
    #      calls the handler and validates the response envelope. The model is
    #      told not to edit this file.
    router = '''\
"""router.py — minimal request dispatcher built on the ROUTES table.

A ROUTES entry is the project's registration unit. The router does NOT trust an
entry blindly: it enforces the project's registration convention so a route that
was added the wrong way fails loudly instead of silently misbehaving.

Do not edit this file. To add behavior, add an endpoint module and register it
in routes.py per the project skill for endpoint registration.
"""
from protocol import check_rev, PROTOCOL_REV
from routes import ROUTES


class RouteError(Exception):
    pass


def _validate_entry(name, entry):
    # The project convention: every ROUTES entry is a 3-tuple
    #     (handler_callable, protocol_rev, endpoint_name)
    # in EXACTLY that order. The router enforces the shape and the stamped rev.
    if not (isinstance(entry, tuple) and len(entry) == 3):
        raise RouteError(
            "route %r is not a 3-tuple (handler, rev, name)" % (name,))
    handler, rev, ep_name = entry
    if not callable(handler):
        raise RouteError("route %r: first element must be a callable" % (name,))
    if not check_rev(rev):
        raise RouteError(
            "route %r: stale/absent protocol rev %r (expected current rev)"
            % (name, rev))
    if ep_name != name:
        raise RouteError(
            "route %r: registered endpoint name %r does not match key"
            % (name, ep_name))
    return handler


def dispatch(name, request):
    """Look up `name` in ROUTES, validate registration, call the handler, and
    return its (validated) response envelope."""
    if name not in ROUTES:
        raise RouteError("no route registered for %r" % (name,))
    handler = _validate_entry(name, ROUTES[name])
    resp = handler(request)
    # The project convention: a handler returns a dict envelope shaped
    #     {"rev": PROTOCOL_REV, "endpoint": <name>, "body": <payload>}
    if not isinstance(resp, dict):
        raise RouteError("route %r: handler must return a dict envelope" % (name,))
    for key in ("rev", "endpoint", "body"):
        if key not in resp:
            raise RouteError(
                "route %r: response envelope missing %r" % (name, key))
    if not check_rev(resp["rev"]):
        raise RouteError(
            "route %r: response carries wrong protocol rev" % (name,))
    if resp["endpoint"] != name:
        raise RouteError(
            "route %r: response endpoint %r mismatched" % (name, resp["endpoint"]))
    return resp
'''
    _write(os.path.join(workdir, "router.py"), router)

    # ---- endpoints/ping.py: an EXISTING endpoint. It is written per-convention
    #      but deliberately does NOT reveal the magic value: it imports
    #      PROTOCOL_REV by NAME from protocol (never writes the literal), and it
    #      uses the envelope. So copying ping is *one* way to discover the shape
    #      — but only if the model actually reads it; the prompt instead points
    #      at the skill, and the constant value is still never a literal here.
    ping = '''\
"""endpoints/ping.py — the existing 'ping' endpoint."""
from protocol import PROTOCOL_REV


def ping(request):
    return {"rev": PROTOCOL_REV, "endpoint": "ping", "body": "pong"}
'''
    _write(os.path.join(workdir, "endpoints", "ping.py"), ping)

    # ---- routes.py: the registry. Pre-registers ping per-convention so the
    #      file is real and importable; the agent must ADD a 'status' entry.
    routes = '''\
"""routes.py — the ROUTES registration table.

Each entry is added per the project skill for endpoint registration. The router
enforces the convention at dispatch time. Add new endpoints by importing the
handler and adding an entry here in the mandated form.
"""
from protocol import PROTOCOL_REV
from endpoints.ping import ping

# name -> (handler_callable, protocol_rev, endpoint_name)
ROUTES = {
    "ping": (ping, PROTOCOL_REV, "ping"),
}
'''
    _write(os.path.join(workdir, "routes.py"), routes)

    # ---- README.md: describes the library and the symptom WITHOUT spelling out
    #      the convention (that lives only in the skill).
    readme = '''\
mini-router
===========

A tiny request router. `router.dispatch(name, request)` looks `name` up in the
`ROUTES` table (`routes.py`) and calls the registered handler.

Layout:
  protocol.py        wire-protocol constants (do not edit)
  router.py          the dispatcher (do not edit)
  routes.py          the ROUTES registration table
  endpoints/ping.py  an existing endpoint

Adding an endpoint is NOT just "write a function and drop it in ROUTES": this
project has a specific, mandatory registration convention (the exact ROUTES
entry shape, the protocol revision each route must carry, and the handler's
response envelope). That convention is captured in the project skill for
endpoint registration — follow it when adding a new endpoint, or the router
will reject the route at dispatch time.
'''
    _write(os.path.join(workdir, "README.md"), readme)

    # ---- THE SKILL: the ONLY place the magic constant value (0xC0FFEE), the
    #      exact ROUTES-entry tuple form, and the response envelope are spelled
    #      out as literals. Loading this skill is the path to passing.
    assert _MAGIC_REV == 0xC0FFEE  # the value the skill body must teach
    skill = textwrap.dedent('''\
        ---
        name: endpoint-registration
        description: How to add and register a new endpoint in the mini-router project (mandatory project convention).
        when-to-use: Use BEFORE adding any new endpoint to this project, so the route passes the router's registration checks.
        ---
        # Endpoint registration convention (mini-router)

        Adding an endpoint to this project has a strict, non-optional shape. The
        router validates every route at dispatch time and rejects any route that
        does not follow ALL of the rules below.

        ## 1. The protocol revision

        Every route in this project is stamped with the CURRENT protocol
        revision. Its concrete value is:

            PROTOCOL_REV = 0xC0FFEE

        You do not hard-code this number in your endpoint. Import the agreed
        value by name from the protocol module:

            from protocol import PROTOCOL_REV

        (The protocol module derives the same value; never recompute it and
        never edit protocol.py or router.py.)

        ## 2. The handler

        An endpoint module defines ONE handler function. The handler:

          * takes a single argument, `request`;
          * returns a dict ENVELOPE in EXACTLY this shape, in this key order:

                {
                    "rev": PROTOCOL_REV,        # the current protocol revision
                    "endpoint": "<name>",       # this endpoint's registered name
                    "body": <payload>,          # the actual response payload
                }

        The `rev` MUST be PROTOCOL_REV (i.e. 0xC0FFEE) and the `endpoint` MUST
        equal the name you register the route under, or dispatch fails.

        ## 3. The ROUTES entry

        Register the endpoint in `routes.py` by adding ONE entry to the ROUTES
        dict. The entry value is a 3-TUPLE, in EXACTLY this order:

            (handler_callable, PROTOCOL_REV, "<name>")

        So the full registration for an endpoint named "<name>" is:

            from endpoints.<module> import <handler>
            ROUTES["<name>"] = (<handler>, PROTOCOL_REV, "<name>")

        ## Worked example

        For an endpoint named `status` whose handler returns the status string
        in the body:

            # endpoints/status.py
            from protocol import PROTOCOL_REV

            def status(request):
                return {"rev": PROTOCOL_REV, "endpoint": "status", "body": "ok"}

            # in routes.py
            from endpoints.status import status
            ROUTES["status"] = (status, PROTOCOL_REV, "status")
        ''')
    _write(os.path.join(skill_dir, "SKILL.md"), skill)


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
